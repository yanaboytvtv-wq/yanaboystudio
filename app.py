uploaded_image = st.file_uploader("อัปโหลดรูปภาพตัวละคร (เพื่อล็อคหน้าตา)", type=["jpg", "jpeg", "png"])

# แสดงตัวอย่างรูปถ้าอัปโหลดแล้ว
if uploaded_image is not None:
    st.image(uploaded_image, caption="รูปตัวละครของคุณบอย/ลูกศิษย์", width=200)

st.markdown("---")

# ส่วนที่ 2: ปุ่มกดสั่งงาน
st.subheader("🚀 ขั้นตอนที่ 2: สร้างคลิปสั้น (10 วินาที)")
